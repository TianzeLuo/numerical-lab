r"""``numcore.pde.fem`` —— 4.4 章「有限元方法」的数值内核。

这一包只回答一个问题：**把一个变分问题离散成矩阵、解出来，并且知道这个解有多准、
以及"有多准"这句话是按哪个范数说的**。四件最容易骗人的事各自对应一个模块：

1. **范数没写清，阶就没有意义**：同一个 :math:`P_1` 解，:math:`L^2` 误差的实测阶是
   :math:`2`、能量范数（:math:`H^1` 半范）的实测阶是 :math:`1`——两条曲线画在同一张
   双对数图上会让人以为"其中一个算错了"（:mod:`~numcore.pde.fem.solve` 的误差范数族）；
2. **对称正定是装出来的、不是假设的**：散射式装配里 :math:`K_{ij}` 与 :math:`K_{ji}`
   收到的贡献来自同一批单元但**加法顺序不同**，于是 :math:`\max|K-K^{\mathsf T}|` 不是
   精确的 0（实测在舍入级）；边界条件用罚函数加会保住对称性却把条件数抬到
   :math:`1/\varepsilon`（:mod:`~numcore.pde.fem.assemble` 的两种约束路径）；
3. **Lax--Milgram / Céa 的前提是可以量出来的**：离散双线性形式的强制性与连续性常数
   就是一对广义特征值，:math:`\sqrt{M_h/\alpha_h}` 直接给出 Céa 界前面的那个常数——
   系数反差大时它会大到让误差界失去分辨力（:mod:`~numcore.pde.fem.solve` 的
   :func:`~numcore.pde.fem.solve.lax_milgram_constants`）；
4. **后验指示子必须与真误差对拍**：指示子的效率指数是一个**分布**而不是一个漂亮的热力图；
   同一个指示子驱动的自适应加密，在尖角解上能把误差从代数衰减扳成几何衰减
   （:mod:`~numcore.pde.fem.adapt`）。

模块边界（谁负责哪个文件）：

========================================  ==========================================================
文件                                      数学对象 / 章内角色
========================================  ==========================================================
:mod:`~numcore.pde.fem.mesh`              **网格与有限元空间**：一维区间网格（顶点 + 单元连接）、
                                          二维三角/双线性四边形网格、均匀与按标记二分加密、
                                          拉格朗日 :math:`P_1/P_2`、Chebyshev--Lobatto 高阶单元素
                                          空间（p-加密用）、Hermite 三次空间（梁用）、
                                          边界自由度、单元直径与二维等参单元的有效性（Jacobi 行列式）
:mod:`~numcore.pde.fem.shape`             **形函数与等参映射**：参考单元上的拉格朗日基（任意节点集，
                                          重心公式）、Hermite 三次基、双线性四边形基、
                                          Gauss--Legendre / 单纯形求积规则、等参映射与其 Jacobi 行列式
:mod:`~numcore.pde.fem.assemble`          **装配**：单元刚度/质量/载荷矩阵、散射式装配与
                                          **装配历史**（可视化用）、三重组、结构对称性、
                                          Dirichlet 条件的消元法与罚函数法、装配一致性残差
:mod:`~numcore.pde.fem.solve`             **求解与误差**：自研 Cholesky/LU 两条路线、解、
                                          :math:`L^2`/能量/ :math:`H^1` 半范误差、
                                          插值（最佳逼近）误差、离散强制性与连续性常数、
                                          条件数、Céa 因子
:mod:`~numcore.pde.fem.adapt`             **后验与自适应**：残差型指示子（单元残差 + 面跳跃）、
                                          Dörfler 标记、自适应与均匀加密的对照、效率指数分布
========================================  ==========================================================

依赖方向：本包只依赖 :mod:`numpy` 的容器与逐元素原语、:mod:`numcore.linalg`（1.2 章的
Cholesky、LU 与 Jacobi 特征分解——**不重复实现线性代数**）与
:mod:`numcore.pde.fem` 内部的四个模块；不 import :mod:`numcore.reference`（P10），
参考实现只出现在 ``tests/4.4/`` 里。四个模块的依赖是单向的：

.. code-block:: text

    mesh  ->  shape  ->  assemble  ->  solve  ->  adapt

也就是"几何 → 形函数 → 矩阵 → 解 → 误差估计"这一个方向，反向没有依赖。
"""

