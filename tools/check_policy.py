_ALLOW_RE = re.compile(r"#\s*policy:\s*allow\s+(P\d+)\b(?P<reason>.*)$")
_GEN_HEADER_RE = re.compile(r"(由 .*生成|generated by|请勿手改|DO NOT EDIT)", re.IGNORECASE)


@dataclass(frozen=True)
class Violation:
    """一条策略违规。"""

    rule: str
    path: str
    line: int
    message: str
    snippet: str
    allowed_hint: str = ""

    def to_dict(self) -> dict[str, object]:
        return asdict(self)

    def __str__(self) -> str:  # pragma: no cover - 人读
        return f"{self.path}:{self.line}: [{self.rule}] {self.message}\n    {self.snippet.strip()}"


def _norm(path: str) -> str:
    p = str(path).replace("\\", "/")
    while p.startswith("./"):
        p = p[2:]
    return p


def _is_allowed(rule: str, path: str) -> bool:
    npath = _norm(path)
    return any(npath.startswith(prefix) for prefix in ALLOWED_PATHS.get(rule, ()))


def _line_of(source_lines: Sequence[str], lineno: int) -> str:
    if 1 <= lineno <= len(source_lines):
        return source_lines[lineno - 1]
    return ""


def comment_allowances(source: str) -> dict[int, list[tuple[str, str]]]:
    """行号 → [(规则, 理由), …]，**只认真正的注释 token**。

    为什么不用逐行正则：文档字符串或测试夹具里出现 ``# policy: allow P1`` 这样的**文字**
    时，逐行正则会误以为有人开了后门（也可能反过来，让真正的违规被"文字"掩盖）。
    ``tokenize`` 能精确区分注释与字符串，这也是本项目"检查器自身必须可信"的一部分。
    """
    out: dict[int, list[tuple[str, str]]] = {}
    try:
        for tok in tokenize.generate_tokens(io.StringIO(source).readline):
            if tok.type == tokenize.COMMENT:
                m = _ALLOW_RE.search(tok.string)
                if m:
                    out.setdefault(tok.start[0], []).append((m.group(1), (m.group("reason") or "").strip()))
    except (tokenize.TokenError, IndentationError, SyntaxError):
        for i, line in enumerate(source.splitlines(), start=1):
            m = _ALLOW_RE.search(line)
            if m:
                out.setdefault(i, []).append((m.group(1), (m.group("reason") or "").strip()))
    return out


def _has_inline_allow(allowances: dict[int, list[tuple[str, str]]], lineno: int, rule: str) -> bool:
    """同一行或上一行是否写了 ``# policy: allow <rule>``。"""
    for ln in (lineno, lineno - 1):
        for r, _reason in allowances.get(ln, ()):
            if r == rule:
                return True
    return False


def _attr_chain(node: ast.AST) -> list[str]:
    """把 ``np.linalg.solve`` 这样的属性链摊平成 ``["np", "linalg", "solve"]``。"""
    parts: list[str] = []
    cur: ast.AST | None = node
    while isinstance(cur, ast.Attribute):
        parts.append(cur.attr)
        cur = cur.value
    if isinstance(cur, ast.Name):
        parts.append(cur.id)
    return list(reversed(parts))


class _PyScanner(ast.NodeVisitor):
    """单文件 AST 扫描器。"""

    def __init__(self, source: str, path: str) -> None:
        self.source_lines = source.splitlines()
        self.path = path
        self.violations: list[Violation] = []
        self.numpy_aliases: set[str] = {"np", "numpy"}
        self.raw = source
        self.allowances = comment_allowances(source)

    # ------------------------------------------------------------------ #
    def add(self, rule: str, node: ast.AST, message: str) -> None:
        lineno = getattr(node, "lineno", 1)
        if _has_inline_allow(self.allowances, lineno, rule):
            return
        self.violations.append(
            Violation(
                rule=rule,
                path=self.path,
                line=lineno,
                message=message,
                snippet=_line_of(self.source_lines, lineno),
                allowed_hint=RULE_DOC.get(rule, ""),
            )
        )

    def in_numcore(self) -> bool:
        return _norm(self.path).startswith("numcore/")

    def is_reference(self) -> bool:
        return _norm(self.path).startswith("numcore/reference/")

    # ------------------------------------------------------------------ #
    def visit_Import(self, node: ast.Import) -> None:  # noqa: N802
        for alias in node.names:
            top = alias.name.split(".")[0]
            self._check_module(node, alias.name, top)
            if top == "numpy":
                self.numpy_aliases.add(alias.asname or "numpy")
            if alias.asname and top == "numpy":
                self.numpy_aliases.add(alias.asname)
            if "." in alias.name:
                parts = alias.name.split(".")
                if top == "numpy" and len(parts) > 1 and parts[1] in P2_SUBMODULES:
                    if not _is_allowed("P2", self.path):
                        self.add("P2", node, f"禁止 import {alias.name}（{RULE_DOC['P2']}）")
                if top == "numpy" and len(parts) > 1 and parts[1] == "random":
                    self._check_random(node)
        self.generic_visit(node)

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:  # noqa: N802
        mod = node.module or ""
        top = mod.split(".")[0]
        self._check_module(node, mod, top)
        parts = mod.split(".")
        if top == "numpy" and len(parts) > 1 and parts[1] in P2_SUBMODULES and not _is_allowed("P2", self.path):
            self.add("P2", node, f"禁止 from {mod} import ...（{RULE_DOC['P2']}）")
        if top == "numpy" and len(parts) > 1 and parts[1] == "random":
            self._check_random(node)
        if top == "numpy" and len(parts) > 1 and parts[1] == "polynomial" and self.in_numcore() and not self.is_reference():
            self.add("P3", node, "禁止 from numpy.polynomial import ...：多项式工具须自研（P3）")
        self.generic_visit(node)

    def _check_module(self, node: ast.AST, full: str, top: str) -> None:
        for rule, mods in BANNED_MODULES.items():
            if top in mods and rule_applies(rule, self.path) and not _is_allowed(rule, self.path):
                self.add(rule, node, f"禁止 import {full}（{RULE_DOC[rule]}）")
        if top == "numcore" and full.split(".")[:2] == ["numcore", "reference"]:
            if not self.is_reference() and not _norm(self.path).startswith(("tests/", "tools/")):
                self.add("P10", node, f"禁止 import {full}：参照物只能出现在测试与工具里（{RULE_DOC['P10']}）")
        if rule_applies("P6", self.path) and self.in_numcore() and not self.is_reference() and top in P6_MODULES:
            self.add("P6", node, f"numcore 内禁止 import {top}（纯函数约束，P6）")

    def _check_random(self, node: ast.AST) -> None:
        if not _is_allowed("P4", self.path):
            self.add("P4", node, f"禁止 numpy.random：请用 numcore.utils.rng（{RULE_DOC['P4']}）")

    def visit_Attribute(self, node: ast.Attribute) -> None:  # noqa: N802
        chain = _attr_chain(node)
        if len(chain) >= 2 and chain[0] in self.numpy_aliases:
            sub = chain[1]
            if sub in P2_SUBMODULES and not _is_allowed("P2", self.path):
                self.add("P2", node, f"禁止 numpy.{sub}.*（{RULE_DOC['P2']}）")
            if sub == "random":
                self._check_random(node)
            if rule_applies("P3", self.path) and self.in_numcore() and not self.is_reference() and sub in P3_ATTRS:
                self.add("P3", node, f"禁止 numpy.{sub}：这是现成求解器，必须自研（P3）")
        if chain and chain[0] in P6_BUILTINS and rule_applies("P6", self.path) and self.in_numcore() and not self.is_reference():
            self.add("P6", node, f"numcore 内禁止 {chain[0]}（纯函数约束，P6）")
        self.generic_visit(node)

    def visit_Call(self, node: ast.Call) -> None:  # noqa: N802
        func = node.func
        # 直接调用内置副作用函数
        if isinstance(func, ast.Name) and func.id in P6_BUILTINS and rule_applies("P6", self.path) and self.in_numcore() and not self.is_reference():
            self.add("P6", node, f"numcore 内禁止 {func.id}()（纯函数约束，P6）")
        # 动态 import 绕过静态检查的常见手法
        if isinstance(func, ast.Attribute) and func.attr in {"import_module", "load_module", "__import__"}:
            if node.args and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str):
                target = node.args[0].value.split(".")[0]
                for rule, mods in BANNED_MODULES.items():
                    if target in mods and rule_applies(rule, self.path) and not _is_allowed(rule, self.path):
                        self.add(rule, node, f"禁止动态 import {node.args[0].value}（{RULE_DOC[rule]}）")
        self.generic_visit(node)

    def visit_Global(self, node: ast.Global) -> None:  # noqa: N802
        if rule_applies("P6", self.path) and self.in_numcore() and not self.is_reference():
            self.add("P6", node, "numcore 内禁止 global 语句（无全局可变状态，P6）")
        self.generic_visit(node)


def scan_source(source: str, *, path: str) -> list[Violation]:
    r"""扫描一段 Python 源码，返回违规列表（纯函数，便于元测试）。

    除了语法错误，这里还把 ``SyntaxWarning`` 升级成违规：最典型的是文档字符串里的
    ``\i`` / ``\m`` 这类无效转义（LaTeX 写法太容易踩）。它们不影响运行，但
    ``python -W error`` 下会直接炸，而且往往意味着作者"以为自己在写 raw 字符串"。
    注意 ``ast.parse`` **会**发这个警告（编译器的 tokenizer 阶段），
    但它默认只显示一次且只打到 stderr——不接住就等于没有检查（这是本规则的第一版真实 bug）。
    """
    import warnings as _warnings

    with _warnings.catch_warnings(record=True) as caught:
        _warnings.simplefilter("always")
        try:
            tree = ast.parse(source, filename=_norm(path))
        except SyntaxError as exc:  # 语法错误本身就是问题
            return [Violation(rule="SYNTAX", path=_norm(path), line=exc.lineno or 1, message=f"语法错误：{exc.msg}", snippet="")]
    out: list[Violation] = []
    for w in caught:
        if not issubclass(w.category, SyntaxWarning):
            continue
        line = int(getattr(w, "lineno", 0) or 0)
        out.append(
            Violation(
                rule="SYNTAX",
                path=_norm(path),
                line=line,
                message=f"警告当作错误：{w.message}（无效转义请写成原始字符串 r\"\"\" 或双反斜杠）",
                snippet=_line_of(source.splitlines(), line),
            )
        )
    scanner = _PyScanner(source, _norm(path))
    scanner.visit(tree)
    return out + scanner.violations


_TS_IMPORT_RE = re.compile(r"""^\s*(?:import|export)\b[^'"]*from\s*['"](?P<mod>[^'"]+)['"]""", re.MULTILINE)
_TS_SIDE_EFFECT_IMPORT_RE = re.compile(r"""^\s*import\s*['"](?P<mod>[^'"]+)['"]""", re.MULTILINE)


def scan_ts_source(source: str, *, path: str) -> list[Violation]:
    """扫描 TypeScript 源码：P7（运行期零依赖）、P8（不得自造物理量）、P12（生成物头部）。"""
    npath = _norm(path)
    out: list[Violation] = []
    is_test = npath.startswith("viz/tests/")
    for m in list(_TS_IMPORT_RE.finditer(source)) + list(_TS_SIDE_EFFECT_IMPORT_RE.finditer(source)):
        mod = m.group("mod")
        line = source[: m.start()].count("\n") + 1
        if mod.startswith(".") or mod.startswith("/"):
            continue
        if mod.startswith("node:") and is_test:
            continue
        rule = "P7"
        out.append(
            Violation(
                rule=rule,
                path=npath,
                line=line,
                message=f"viz 运行期禁止第三方 import：{mod!r}（{RULE_DOC[rule]}）",
                snippet=m.group(0).strip(),
                allowed_hint=RULE_DOC[rule],
            )
        )
    if npath.startswith("viz/chapters/") and re.search(r"""from\s*['"][^'"]*numeric/[^'"]*['"]""", source):
        if "preview-approx" not in source:
            out.append(
                Violation(
                    rule="P8",
                    path=npath,
                    line=1,
                    message="章节前端调用了 shared/numeric：必须在文件中标注 // preview-approx（P8）",
                    snippet="",
                    allowed_hint=RULE_DOC["P8"],
                )
            )
    if npath.endswith(".gen.ts") and not _GEN_HEADER_RE.search(source[:600]):
        out.append(
            Violation(
                rule="P12",
                path=npath,
                line=1,
                message="生成物文件缺少「本文件由…生成 / 请勿手改」头部声明（P12）",
                snippet=source.splitlines()[0] if source else "",
                allowed_hint=RULE_DOC["P12"],
            )
        )
    return out


def iter_py_files(root: pathlib.Path) -> Iterable[pathlib.Path]:
    for d in PY_DIRS:
        base = root / d
        if not base.exists():
            continue
        for p in sorted(base.rglob("*.py")):
            if any(part in SKIP_DIR_NAMES for part in p.parts):
                continue
            yield p


def iter_ts_files(root: pathlib.Path) -> Iterable[pathlib.Path]:
    for d in TS_DIRS:
        base = root / d
        if not base.exists():
            continue
        for p in sorted(base.rglob("*.ts")):
            if any(part in SKIP_DIR_NAMES for part in p.parts):
                continue
            yield p


MIN_PITFALL_DOC_CHARS = 800
"""``chapters/<id>/pitfalls.md`` 的最少字数（POLICY §2 第 5 项）。"""

_THEOREM_RE = re.compile(r"\\begin\{theorem\}")


def check_chapter_docs(root: pathlib.Path) -> list[Violation]:
    """P13：章内文档五件套。

    判定范围刻意是"**开了的**章"——目录 ``chapters/<id>/`` 存在（或
    ``server/chapters/<id>.py`` 存在）就算开了。还没开的章不报违规，
    否则 M0 阶段整仓库会一直红；但一旦开了，四份文档必须齐（模块本身由注册表检查）。
    """
    out: list[Violation] = []
    started: set[str] = set()
    chap_dir = root / "chapters"
    if chap_dir.is_dir():
        for d in sorted(chap_dir.iterdir()):
            if d.is_dir() and not d.name.startswith((".", "_")):
                started.add(d.name)
    srv_dir = root / "server" / "chapters"
    if srv_dir.is_dir():
        for f in sorted(srv_dir.glob("*.py")):
            if not f.name.startswith("_"):
                started.add(f.stem)

    for cid in sorted(started):
        base = chap_dir / cid
        notes = base / "notes.tex"
        if not notes.exists():
            out.append(
                Violation(
                    rule="P13",
                    path=f"chapters/{cid}/notes.tex",
                    line=1,
                    message=f"章节 {cid} 缺推导笔记 notes.tex（POLICY §2 第 1 项）",
                    snippet="",
                    allowed_hint=RULE_DOC["P13"],
                )
            )
        elif not _THEOREM_RE.search(notes.read_text(encoding="utf-8", errors="replace")):
            out.append(
                Violation(
                    rule="P13",
                    path=f"chapters/{cid}/notes.tex",
                    line=1,
                    message=f"章节 {cid} 的 notes.tex 里没有 \\begin{{theorem}}：关键定理必须给出完整证明",
                    snippet="",
                    allowed_hint=RULE_DOC["P13"],
                )
            )
        pitfalls = base / "pitfalls.md"
        if not pitfalls.exists():
            out.append(
                Violation(
                    rule="P13",
                    path=f"chapters/{cid}/pitfalls.md",
                    line=1,
                    message=f"章节 {cid} 缺防误导分析 pitfalls.md（POLICY §2 第 5 项）",
                    snippet="",
                    allowed_hint=RULE_DOC["P13"],
                )
            )
        else:
            n = len(pitfalls.read_text(encoding="utf-8", errors="replace").strip())
            if n < MIN_PITFALL_DOC_CHARS:
                out.append(
                    Violation(
                        rule="P13",
                        path=f"chapters/{cid}/pitfalls.md",
                        line=1,
                        message=f"章节 {cid} 的 pitfalls.md 只有 {n} 字，少于 {MIN_PITFALL_DOC_CHARS} 字",
                        snippet="",
                        allowed_hint=RULE_DOC["P13"],
                    )
                )
        decl = base / "asserts.yaml"
        if not decl.exists():
            out.append(
                Violation(
                    rule="P13",
                    path=f"chapters/{cid}/asserts.yaml",
                    line=1,
                    message=f"章节 {cid} 缺断言声明 asserts.yaml（POLICY §2 第 4 项）",
                    snippet="",
                    allowed_hint=RULE_DOC["P13"],
                )
            )
    return out


def check_package_json(root: pathlib.Path) -> list[Violation]:
    """P7：``package.json`` 不得有运行期依赖，devDependencies 只允许白名单。"""
    pkg = root / "package.json"
    if not pkg.exists():
        return []
    data = json.loads(pkg.read_text(encoding="utf-8"))
    out: list[Violation] = []
    if data.get("dependencies"):
        out.append(
            Violation(
                rule="P7",
                path="package.json",
                line=1,
                message=f"禁止运行期依赖：{sorted(data['dependencies'])}（{RULE_DOC['P7']}）",
                snippet=json.dumps(data["dependencies"], ensure_ascii=False),
                allowed_hint=RULE_DOC["P7"],
            )
        )
    allowed_dev = {"typescript", "@types/node"}
    extra = set(data.get("devDependencies", {})) - allowed_dev
    if extra:
        out.append(
            Violation(
                rule="P7",
                path="package.json",
                line=1,
                message=f"devDependencies 只允许 {sorted(allowed_dev)}，多出：{sorted(extra)}",
                snippet=json.dumps(data.get("devDependencies", {}), ensure_ascii=False),
                allowed_hint=RULE_DOC["P7"],
            )
        )
    return out


def load_registered_allowlist(root: pathlib.Path) -> set[str]:
    """读取已登记的豁免（``tests/policy/allowlist.txt``，每行 ``路径:规则``）。"""
    f = root / "tests" / "policy" / "allowlist.txt"
    if not f.exists():
        return set()
    return {ln.strip() for ln in f.read_text(encoding="utf-8").splitlines() if ln.strip() and not ln.startswith("#")}


_TS_ALLOW_RE = re.compile(r"//\s*policy:\s*allow\s+(P\d+)\b(?P<reason>.*)$")


def find_inline_allows(root: pathlib.Path) -> list[tuple[str, int, str, str]]:
    """找出源码里所有行内豁免（含未登记的）。Python 用 tokenize，TypeScript 用正则。"""
    found: list[tuple[str, int, str, str]] = []
    for p in iter_py_files(root):
        rel = _norm(str(p.relative_to(root)))
        text = p.read_text(encoding="utf-8", errors="replace")
        for lineno, items in comment_allowances(text).items():
            for rule, reason in items:
                found.append((rel, lineno, rule, reason))
    for p in iter_ts_files(root):
        rel = _norm(str(p.relative_to(root)))
        for i, line in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), start=1):
            m = _TS_ALLOW_RE.search(line)
            if m:
                found.append((rel, i, m.group(1), (m.group("reason") or "").strip()))
    return found


def check(root: pathlib.Path) -> tuple[list[Violation], list[str]]:
    """全仓库检查，返回 ``(违规, 提示)``。"""
    violations: list[Violation] = []
    notes: list[str] = []
    for p in iter_py_files(root):
        rel = _norm(str(p.relative_to(root)))
        violations.extend(scan_source(p.read_text(encoding="utf-8", errors="replace"), path=rel))
    for p in iter_ts_files(root):
        rel = _norm(str(p.relative_to(root)))
        violations.extend(scan_ts_source(p.read_text(encoding="utf-8", errors="replace"), path=rel))
    violations.extend(check_package_json(root))
    violations.extend(check_chapter_docs(root))
    notes.append("P6 文件级豁免（测试基础设施）：" + ", ".join(P6_EXEMPT_FILES))
    registered = load_registered_allowlist(root)
    for rel, lineno, rule, reason in find_inline_allows(root):
        key = f"{rel}:{rule}"
        if key not in registered:
            violations.append(
                Violation(
                    rule="ALLOWLIST",
                    path=rel,
                    line=lineno,
                    message=f"未登记的豁免 {key}（请在 tests/policy/allowlist.txt 登记，理由：{reason or '（无）'}）",
                    snippet="",
                )
            )
    return violations, notes


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="仓库策略静态检查（docs/POLICY.md 的执行体）")
    ap.add_argument("--root", default=str(_ROOT))
    ap.add_argument("--json", dest="json_path", default=None, help="把结果写入 JSON（缺省 dist/reports/policy.json）")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)
    root = pathlib.Path(args.root).resolve()
    violations, notes = check(root)
    out_path = pathlib.Path(args.json_path) if args.json_path else root / "dist" / "reports" / "policy.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(
        json.dumps(
            {
                "ok": not violations,
                "n_violations": len(violations),
                "violations": [v.to_dict() for v in violations],
                "rules": RULE_DOC,
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )
    if violations:
        print(f"策略检查未通过：{len(violations)} 条违规")
        by_rule: dict[str, int] = {}
        for v in violations:
            by_rule[v.rule] = by_rule.get(v.rule, 0) + 1
            if not args.quiet:
                print(f"  {v}")
        print("  按规则统计：" + ", ".join(f"{k}×{n}" for k, n in sorted(by_rule.items())))
        print(f"  详情：{out_path}")
        return 1
    print(f"策略检查通过：{len(RULE_DOC)} 条规则、0 违规（报告：{out_path}）")
    for n in notes:
        print(f"  提示：{n}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
