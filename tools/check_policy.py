#: 规则生效范围：返回 True 表示该规则适用于此文件
def rule_applies(rule: str, path: str) -> bool:
    """规则作用域（路径已归一化）。"""
    npath = _norm(path)
    if rule in ("P1", "P2"):
        return True  # 全仓库：Python 侧的"现成求解器"只有 reference/ 可以用
    if rule in ("P3", "P5"):
        return npath.startswith("numcore/")  # 自研约束只针对数值核心
    if rule == "P6":
        return npath.startswith("numcore/") and not any(npath.startswith(f) for f in P6_EXEMPT_FILES)
    if rule == "P10":
        return npath.startswith(("numcore/", "server/", "viz/"))
    return True


