"""``check_policy.py`` —— 把 ``docs/POLICY.md`` 变成可执行的门禁（CI 门禁 G1）。

设计原则：**检查器自身必须可测**。因此核心逻辑是纯函数
``scan_source(source, path) -> list[Violation]``，`tests/policy/test_check_policy.py`
用合成代码逐条喂给它，验证"该报的报、不该报的不报"。

豁免机制：源码行上写 ``# policy: allow P<n> <理由>`` 可豁免该行的对应规则，
但必须在 ``tests/policy/allowlist.txt`` 登记（``路径:规则`` 每行一条），
否则视为"未登记豁免"并报违规——防止有人用注释悄悄开后门。
"""

